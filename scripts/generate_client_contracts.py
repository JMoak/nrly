"""Generate the SDK input types from the authoritative Pydantic schemas."""

from __future__ import annotations

import argparse
import importlib
import json
from pathlib import Path
from typing import Any

from pydantic import BaseModel

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / "packages" / "client" / "src" / "contracts.generated.ts"


def render_type(schema: dict[str, Any]) -> str:
    if "$ref" in schema:
        return str(schema["$ref"]).rsplit("/", 1)[-1]
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(json.dumps(value) for value in schema["enum"])
    if "anyOf" in schema or "oneOf" in schema:
        variants = schema["anyOf"] if "anyOf" in schema else schema["oneOf"]
        return " | ".join(render_type(item) for item in variants)
    kind = schema.get("type", "unknown")
    if kind == "array":
        return f"Array<{render_type(schema.get('items', {}))}>"
    if kind == "object":
        properties = schema.get("properties", {})
        required = schema.get("required", [])
        if not properties:
            values = schema.get("additionalProperties", {})
            return (
                f"Record<string, {render_type(values) if isinstance(values, dict) else 'unknown'}>"
            )
        fields = [
            f"  {json.dumps(key)}{'' if key in required else '?'}: {render_type(value)};"
            for key, value in properties.items()
        ]
        return "{\n" + "\n".join(fields) + "\n}"
    return {
        "string": "string",
        "integer": "number",
        "number": "number",
        "boolean": "boolean",
        "null": "null",
    }.get(kind, "unknown")


def generate() -> str:
    schemas: dict[str, dict[str, Any]] = {}
    for module_name in (
        "nrly.contracts",
        "nrly.study_contracts",
        "nrly.artifacts",
        "nrly.lineage",
        "nrly.deployment",
    ):
        module = importlib.import_module(module_name)
        for name, model in vars(module).items():
            if (
                isinstance(model, type)
                and issubclass(model, BaseModel)
                and model.__module__ == module_name
                and name != "Contract"
            ):
                schema = model.model_json_schema()
                schemas.update(schema.pop("$defs", {}))
                schemas[name] = schema
    lines = ["// Generated by scripts/generate_client_contracts.py; do not edit by hand.", ""]
    for name, schema in sorted(schemas.items()):
        lines.append(f"export type {name} = {render_type(schema)};\n")
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    result = generate()
    if args.check:
        if not TARGET.exists() or TARGET.read_text(encoding="utf-8") != result:
            raise SystemExit("Client contracts are stale; run scripts/generate_client_contracts.py")
    else:
        TARGET.parent.mkdir(parents=True, exist_ok=True)
        TARGET.write_text(result, encoding="utf-8")


if __name__ == "__main__":
    main()
