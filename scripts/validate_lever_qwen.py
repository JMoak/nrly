"""Real cached Qwen3-0.6B lever acceptance: derive, dial, referee, map. Authored smoke.

The behaviour is reply-only compliance. Asked to answer a multiple-choice question with
only the option letter, the unedited model elaborates instead. The recipe contrasts those
zero-shot prompts with the same kind of question preceded by demonstrations, where the
model does answer with a bare letter, and removes the separating direction from the
output of one MLP.

Every prompt, including the "holdout", is generated by this public script. That tests
the one-shot referee mechanism on a real model; it is not a secret research holdout, and
nothing here establishes a generally useful repair. Whatever the verdict, it is recorded.
"""

from __future__ import annotations

import argparse
import json
import os
import random
import time
from pathlib import Path

from nrly.artifacts import write_immutable
from nrly.contracts import (
    BudgetSpec,
    CaseSpec,
    ChatMessage,
    GenerationSpec,
    ModelSpec,
    TaskAdapterSpec,
    canonical_json,
)
from nrly.lever_app import (
    DeriveRequest,
    DialRequest,
    RefereeRequest,
    derive_lever,
    dial_lever,
    lever_map,
    nominate_lever,
    referee_lever,
)
from nrly.lever_contracts import LeverSite, RecipeSpec
from nrly.lever_report import render_lever, render_map
from nrly.study_contracts import ComparatorSpec, InferenceRule

LETTERS = "ABCD"
TAIL = "Reply with only the letter of the correct option."
GROUPS = {
    "fruit": (
        ["apple", "banana", "cherry", "grape", "lemon", "mango", "peach", "pear"],
        ["chair", "hammer", "river", "pencil", "window", "bridge", "candle", "ladder"],
    ),
    "animal": (
        ["horse", "tiger", "rabbit", "eagle", "dolphin", "spider", "camel", "otter"],
        ["table", "spoon", "cloud", "bottle", "carpet", "engine", "mirror", "pillow"],
    ),
    "colour": (
        ["red", "blue", "green", "yellow", "purple", "orange", "pink", "brown"],
        ["seven", "monday", "square", "loud", "paper", "winter", "north", "salt"],
    ),
}
CAPITALS = [
    ("France", "Paris"), ("Japan", "Tokyo"), ("Italy", "Rome"), ("Spain", "Madrid"),
    ("Germany", "Berlin"), ("Egypt", "Cairo"), ("Russia", "Moscow"), ("China", "Beijing"),
    ("Greece", "Athens"), ("Portugal", "Lisbon"), ("Ireland", "Dublin"), ("Austria", "Vienna"),
    ("Norway", "Oslo"), ("Poland", "Warsaw"), ("Peru", "Lima"), ("Cuba", "Havana"),
    ("Kenya", "Nairobi"), ("Sweden", "Stockholm"), ("Finland", "Helsinki"),
    ("Hungary", "Budapest"), ("Canada", "Ottawa"), ("Turkey", "Ankara"),
    ("Thailand", "Bangkok"), ("Vietnam", "Hanoi"), ("Belgium", "Brussels"),
    ("Denmark", "Copenhagen"), ("Chile", "Santiago"), ("Iran", "Tehran"),
    ("Iraq", "Baghdad"), ("Romania", "Bucharest"), ("Bulgaria", "Sofia"),
    ("Croatia", "Zagreb"),
]  # fmt: skip


def question(rng: random.Random) -> tuple[str, str]:
    kind = rng.choice([*GROUPS, "largest", "smallest", "sum"])
    options: list[object]
    if kind in GROUPS:
        right: object = rng.choice(GROUPS[kind][0])
        options = [right, *rng.sample(GROUPS[kind][1], 3)]
        text = f"Which of these is {'an' if kind == 'animal' else 'a'} {kind}?"
    elif kind in {"largest", "smallest"}:
        values = rng.sample(range(10, 99), 4)
        right = max(values) if kind == "largest" else min(values)
        options, text = list(values), f"Which of these numbers is the {kind}?"
    else:
        a, b = rng.randint(1, 9), rng.randint(1, 9)
        right = a + b
        options = [right, *rng.sample([v for v in range(2, 19) if v != right], 3)]
        text = f"What is {a} + {b}?"
    rng.shuffle(options)
    lines = "\n".join(f"{letter}) {value}" for letter, value in zip(LETTERS, options, strict=True))
    return f"{text}\n{lines}\n{TAIL}", LETTERS[options.index(right)]


def questions(count: int) -> list[tuple[str, str]]:
    rng = random.Random(20261120)
    seen: dict[str, str] = {}
    while len(seen) < count:
        text, answer = question(rng)
        seen.setdefault(text, answer)
    return list(seen.items())


def evaluation_cases(
    items: list[tuple[str, str]], capitals: list[tuple[str, str]], split: str
) -> list[CaseSpec]:
    choice = TaskAdapterSpec(kind="multiple_choice", choices=list(LETTERS))
    targets = [
        CaseSpec(
            id=f"{split}-letter-{index}", input=text, expected=answer, adapter=choice,
            split=split, group="letter-only",
        )  # fmt: skip
        for index, (text, answer) in enumerate(items)
    ]
    regressions = [
        CaseSpec(
            id=f"{split}-capital-{country.lower()}",
            input=f"What is the capital of {country}? Answer with one word.",
            expected=capital, split=split, role="regression", group="one-word",
        )  # fmt: skip
        for country, capital in capitals
    ]
    return targets + regressions


def stage(name: str, **detail: object) -> None:
    print(json.dumps({"stage": name, **detail}), flush=True)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--cache", type=Path, default=Path(".cache/models"))
    parser.add_argument("--evidence", type=Path, help="write the shareable record here")
    args = parser.parse_args()
    if args.output.exists() or (args.evidence is not None and args.evidence.exists()):
        raise FileExistsError("keep prior attempts; choose new output directories")
    os.environ["HF_HUB_OFFLINE"] = "1"
    os.environ["HF_HUB_DISABLE_PROGRESS_BARS"] = "1"
    os.environ["TOKENIZERS_PARALLELISM"] = "false"
    cache = args.cache.resolve()
    model = ModelSpec.model_validate_json(Path("recipes/qwen-model.json").read_bytes())

    # Disjoint pools: demonstrations, recipe prompts, development, and holdout.
    pool = questions(4 + 32 + 24 + 24)
    demos, contrast = pool[:4], pool[4:36]
    development = evaluation_cases(pool[36:60], CAPITALS[:16], "discovery")
    holdout = evaluation_cases(pool[60:84], CAPITALS[16:], "test")
    shots = [
        ChatMessage(role=role, content=content)
        for text, answer in demos
        for role, content in (("user", text), ("assistant", answer))
    ]
    recipe = RecipeSpec(
        behavior="reply-only.letter",
        # Zero-shot: the model elaborates. With demonstrations: it answers with a bare letter.
        positive=[
            CaseSpec(id=f"zero-shot-{i}", input=text) for i, (text, _) in enumerate(contrast)
        ],
        negative=[
            CaseSpec(
                id=f"demonstrated-{i}", messages=[*shots, ChatMessage(role="user", content=text)]
            )
            for i, (text, _) in enumerate(contrast)
        ],
        sites=[
            LeverSite(
                parameter=f"model.layers.{layer}.mlp.down_proj.weight",
                module=f"model.layers.{layer}.mlp",
                layer=layer,
            )
            for layer in range(28)
        ],
    )
    generation = GenerationSpec(max_new_tokens=8, temperature=0.0, enable_thinking=False)
    budget = BudgetSpec(wall_seconds=1800, max_cases=64, max_output_tokens=1024)
    rule = InferenceRule(regression_margin=0.05)
    started = time.perf_counter()

    stage("derive", prompts=len(recipe.positive) + len(recipe.negative), sites=len(recipe.sites))
    derived = derive_lever(args.output, DeriveRequest(model=model, recipe=recipe), cache)
    stage("derived", chosen=derived["chosen_site"], controls=derived["controls"])

    strengths = [0.5, 1.0, 1.5, 2.0, 3.0]
    # Elaborating past the token limit is the failure under study, so it is registered as
    # a scored failure instead of being left unscored.
    dial_request = DialRequest(
        model=model, cases=development, strengths=strengths, generation=generation,
        seeds=[0], rule=rule, budget=budget, truncation="fail",
    )  # fmt: skip
    stage("dial", strengths=strengths, cases=len(development))
    dialled = dial_lever(args.output, derived["entry_id"], dial_request, cache)
    stage("dialled", nominated=dialled["nominated"], window=dialled["window"])
    entry_id = dialled["entry_id"]
    forced = None
    if dialled["nominated"] is None:
        # No working strength. Referee the strongest target effect anyway so the null is
        # struck on held-out cases instead of being quietly dropped.
        best = max(
            dialled["points"], key=lambda p: p["inference"]["target"]["mean_difference"]
        )
        forced = best["strength"]
        stage("nominate_without_window", strength=forced)
        entry_id = nominate_lever(args.output, entry_id, forced)["entry_id"]

    referee_request = RefereeRequest(
        model=model, development_cases=development, generation=generation, inference=rule,
        run_budget=budget, truncation="fail",
        comparators=[
            ComparatorSpec(
                name="stricter-instruction", kind="prompt",
                suffix=" Reply with the answer only, no other words.",
            )
        ],
    )  # fmt: skip
    stage("referee", development=len(development), holdout=len(holdout))
    refereed = referee_lever(args.output, entry_id, referee_request, holdout, cache)
    stage("refereed", status=refereed["status"], verdict=refereed.get("verdict"))

    levers = lever_map(args.output)
    final = levers.get(refereed["entry_id"])
    summary = {
        "scope": "public real-model lever acceptance; authored smoke; no general quality claim",
        "model": model.model_dump(mode="json"),
        "base": final.base.model_dump(mode="json"),
        "behavior": final.behavior,
        "entry_id": final.id,
        "history": [item.id for item in levers.history(final.id)],
        "status": final.status,
        "chosen_site": derived["chosen_site"],
        "site_scores": derived["scores"],
        "controls": derived["controls"],
        "dial": {
            "evidence": dialled["evidence"],
            "window": dialled["window"],
            "nominated_by_dial": dialled["nominated"],
            "nominated_by_operator_without_window": forced,
            "points": dialled["points"],
            "failed": dialled["failed"],
        },
        "referee": refereed,
        "holdout_disclosure": "holdout prompts are generated by this public script",
        "elapsed_seconds": round(time.perf_counter() - started, 1),
    }
    write_immutable(args.output, "summary.json", canonical_json(summary).encode("utf-8"))
    write_immutable(args.output, "map.html", render_map([final], layers=28).encode("utf-8"))
    if args.evidence is not None:
        # The shareable record: aggregates and the map page, never prompts or outputs.
        write_immutable(args.evidence, "summary.json", canonical_json(summary).encode("utf-8"))
        write_immutable(args.evidence, "lever.html", render_lever(final).encode("utf-8"))
        write_immutable(args.evidence, "map.html", render_map([final], layers=28).encode("utf-8"))
        public = final.model_dump(mode="json")
        if public.get("derivation"):
            # Contrast prompts stay in the local store; the record keeps their counts.
            recipe_view = public["derivation"]["recipe"]
            for name in ("positive", "negative"):
                recipe_view[name + "_count"] = len(recipe_view.pop(name))
        write_immutable(
            args.evidence, "entry-redacted.json",
            json.dumps(public, sort_keys=True, ensure_ascii=False).encode("utf-8"),
        )  # fmt: skip
    stage("done", status=final.status, seconds=summary["elapsed_seconds"])


if __name__ == "__main__":
    main()
